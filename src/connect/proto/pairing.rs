/// The bearer token that authenticates steps 6 through 8 of one pairing attempt.
///
/// `S2C-OAS pairing/PairingAttemptId`: "a random string with a minimal length of 32
/// characters… generated by a cryptographically secure pseudorandom number generator. The
/// recommended method is to generate 24 random bytes and Base64 encode them."
#[derive(Clone, Zeroize, ZeroizeOnDrop, Serialize, Deserialize)]
#[serde(transparent)]
pub struct PairingAttemptId(String);

impl PairingAttemptId {
    /// The fewest characters the specification allows.
    pub const MIN_LEN: usize = 32;

    /// Wrap an identifier received from a peer.
    #[must_use]
    pub fn new(value: impl Into<String>) -> Self {
        Self(value.into())
    }

    /// Generate one from the recommended 24 bytes of entropy.
    pub fn from_entropy(bytes: &[u8]) -> Result<Self, ConnectError> {
        // 24 bytes Base64-encode to exactly the 32 characters the minimum requires.
        if bytes.len() < 24 {
            return Err(ConnectError::WeakSecret {
                got: bytes.len(),
                need: 24,
            });
        }
        Ok(Self(super::base64_encode(bytes)))
    }

    /// The string, which is what travels in `Authorization: Bearer …`.
    #[must_use]
    pub fn as_str(&self) -> &str {
        &self.0
    }

    /// Whether a presented identifier is this one, compared in constant time.
    #[must_use]
    pub fn verify(&self, presented: &str) -> bool {
        use subtle::ConstantTimeEq as _;
        self.0.len() == presented.len() && bool::from(self.0.as_bytes().ct_eq(presented.as_bytes()))
    }
}

impl core::fmt::Debug for PairingAttemptId {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        f.write_str("PairingAttemptId(<redacted>)")
    }
}

