//! Pairing as a state machine that refuses to advance when a rule is broken.
//!
//! The exchange is a **two-way** challenge–response, and the two directions are not
//! symmetrical in time: the client challenges first and the server answers in the same
//! round trip, then the server's challenge is answered one request later. Getting that
//! order wrong produces something that looks like authentication and proves nothing.
//!
//! ```text
//!   HTTPS client                                      HTTPS server
//!   ────────────                                      ────────────
//!   1. generate C_c
//!      POST /v1/requestPairing ───────────────────▶   2. R_c = HMAC(C_c, T ‖ binding)
//!         clientNodeDescription, C_c,                    (rate-limited, ≥ 1 s delay)
//!         versions, protocols, algorithms                generate C_s, attempt id
//!   4. check R_c                ◀───────────────────3. pairingAttemptId, R_c, C_s,
//!   5. R_s = HMAC(C_s, T ‖ binding)                     serverNodeDescription
//!   6A. POST /v1/requestConnectionDetails ───────▶   7A. check R_s
//!          R_s                  ◀───────────────────    ConnectionDetails
//!    or
//!   6B. POST /v1/postConnectionDetails ──────────▶   7B. check R_s
//!          R_s, ConnectionDetails
//!   8. POST /v1/finalizePairing {success} ───────▶   both sides store the pairing
//! ```
//!
//! Which of 6A and 6B applies is decided by [`Deployment::communication_server`], not by
//! preference: the side that will be the *communication* server is the side that has
//! connection details to give.
//!
//! `R_c` proves the server holds the pairing token **and** that the TLS identity answering
//! is the one the token was meant for — its leaf-certificate fingerprint in a LAN, its
//! domain name otherwise. `R_s` proves the client holds the token. Steps 2 through 8 are
//! authenticated by the `pairingAttemptId` the server issues, which is a bearer token.

