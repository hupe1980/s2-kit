/// How far a pairing attempt has got.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum PairingStep {
    /// Nothing has been sent.
    Start,
    /// `requestPairing` has been sent; the server's answer has not arrived.
    AwaitingAcceptance,
    /// `R_c` is verified; connection details have not been exchanged.
    Authenticated,
    /// Connection details are known; `finalizePairing` has not been sent.
    DetailsExchanged,
    /// The pairing is complete and may be stored.
    Paired,
    /// The attempt failed and may not be resumed.
    Failed,
}

impl PairingStep {
    const fn name(self) -> &'static str {
        match self {
            PairingStep::Start => "the start of pairing",
            PairingStep::AwaitingAcceptance => "the server's acceptance",
            PairingStep::Authenticated => "connection details",
            PairingStep::DetailsExchanged => "finalization",
            PairingStep::Paired => "a completed pairing",
            PairingStep::Failed => "a failed pairing",
        }
    }
}

/// Which of steps 6A and 6B the client must take next.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum NextStep {
    /// 6A — the pairing server will be the communication server, so ask it for details.
    RequestConnectionDetails,
    /// 6B — the pairing *client* will be the communication server, so send details.
    PostConnectionDetails,
}

/// The pairing client: the side that types in the code and makes the HTTPS requests.
///
/// ```
/// # use s2_kit::connect::proto::*;
/// # use s2_kit::types::Timestamp;
/// # fn me() -> NodeDescription { NodeDescription {
/// #   id: NodeId::parse("cem-1").unwrap(), brand: "Acme".into(), logo_url: None,
/// #   kind: "CEM".into(), model_name: "Hub".into(), user_defined_name: None,
/// #   role: Role::Cem } }
/// let code = PairingCode::parse("evse7-A1b2C3", TokenKind::Static)?;
/// let now = Timestamp::from_unix(1_700_000_000, 0);
///
/// let mut client = PairingClient::start(me(), EndpointDescription::default(), code, now);
/// let body = client.request_pairing(&[0xA5; 32])?;
/// assert_eq!(client.step(), PairingStep::AwaitingAcceptance);
/// // The alias from the code names the node; `nodeId` stays unset, as the spec requires.
/// assert!(body.node_id.is_none());
/// assert_eq!(body.node_id_alias.as_ref().unwrap().0, "evse7");
/// # Ok::<(), Box<dyn core::error::Error>>(())
/// ```
#[derive(Debug)]
pub struct PairingClient {
    local: NodeDescription,
    local_endpoint: EndpointDescription,
    code: super::PairingCode,
    /// Known only once the server has presented a certificate, which is why it arrives
    /// with [`PairingClient::accept`] rather than at the start.
    binding: Option<HmacBinding>,
    started: Timestamp,
    step: PairingStep,
    /// `C_c`, kept so the server's `R_c` can be checked against it in step 4.
    challenge: Option<Vec<u8>>,
    s2_message_versions: Vec<ProtocolVersion>,
    protocols: Vec<CommunicationProtocol>,
    force: bool,
    accepted: Option<PairingAccepted>,
    details: Option<ConnectionDetails>,
    communication_server: Option<Role>,
}

impl PairingClient {
    /// Begin an attempt. The fifteen-second clock starts here.
    #[must_use]
    pub fn start(
        local: NodeDescription,
        local_endpoint: EndpointDescription,
        code: super::PairingCode,
        now: Timestamp,
    ) -> Self {
        Self {
            local,
            local_endpoint,
            code,
            binding: None,
            started: now,
            step: PairingStep::Start,
            challenge: None,
            // Both, newest first — the deployed ecosystem still negotiates the beta.
            s2_message_versions: alloc::vec![
                crate::types::WireProfile::V1_0_0.connect_version(),
                crate::types::WireProfile::V0_0_2Beta.connect_version(),
            ],
            protocols: alloc::vec![CommunicationProtocol::WebSocket],
            force: false,
            accepted: None,
            details: None,
            communication_server: None,
        }
    }

    /// Offer a different set of S2 JSON message versions, newest first.
    #[must_use]
    pub fn with_s2_message_versions(mut self, versions: Vec<ProtocolVersion>) -> Self {
        self.s2_message_versions = versions;
        self
    }

    /// Pair even with no S2 message version in common.
    ///
    /// The two nodes will not be able to talk until one of them is updated, which is
    /// exactly what the flag is for: `S2C-OAS pairing` calls it out as something "could
    /// later be solved through a software update".
    #[must_use]
    pub fn forcing(mut self) -> Self {
        self.force = true;
        self
    }

    /// How far the attempt has got.
    #[must_use]
    pub const fn step(&self) -> PairingStep {
        self.step
    }

    /// The bearer for steps 6 through 8, once the server has issued one.
    #[must_use]
    pub fn attempt_id(&self) -> Option<&PairingAttemptId> {
        self.accepted.as_ref().map(|a| &a.pairing_attempt_id)
    }

    /// Step 1: build `requestPairing` from 32 bytes of cryptographically secure
    /// randomness.
    ///
    /// The randomness is a parameter because this layer has no business drawing it: a
    /// test needs it pinned, and a driver knows where the system's entropy lives.
    pub fn request_pairing(&mut self, challenge: &[u8]) -> Result<PairingRequest, ConnectError> {
        self.expect(PairingStep::Start)?;
        if challenge.len() < 32 {
            self.step = PairingStep::Failed;
            return Err(ConnectError::WeakSecret {
                got: challenge.len(),
                need: 32,
            });
        }
        self.challenge = Some(challenge.to_vec());
        self.step = PairingStep::AwaitingAcceptance;
        Ok(PairingRequest {
            client_node_description: self.local.clone(),
            client_endpoint_description: self.local_endpoint.clone(),
            // "may never be used at the same time" — the alias wins, because it is what
            // the user typed.
            node_id: None,
            node_id_alias: self.code.alias.clone(),
            supported_communication_protocols: self.protocols.clone(),
            supported_s2_message_versions: self.s2_message_versions.clone(),
            supported_hmac_hashing_algorithms: alloc::vec![HmacHashingAlgorithm::Sha256],
            client_hmac_challenge: super::base64_encode(challenge),
            force_pairing: self.force,
        })
    }

    /// Step 4: check `clientHmacChallengeResponse`, and decide which of 6A and 6B follows.
    ///
    /// This is the moment the client learns it is talking to something that holds the same
    /// pairing token *and* is the TLS identity the token was meant for. A man in the
    /// middle who terminates TLS with his own certificate computes a different `R_c` and
    /// is refused here.
    ///
    /// `S2C §4`: "in case of a local server, the TLS certificate fingerprint is part of
    /// the challenge. So if the challenge succeeds, the certificate fingerprint is
    /// correct, and the certificate can be trusted. The client **must** pin the
    /// self-signed CA (root) certificate."
    pub fn accept(
        &mut self,
        accepted: PairingAccepted,
        binding: HmacBinding,
        local_deployment: Deployment,
        now: Timestamp,
    ) -> Result<NextStep, ConnectError> {
        self.expect(PairingStep::AwaitingAcceptance)?;
        self.within_budget(now)?;
        self.binding = Some(binding);

        if !self
            .local
            .role
            .can_pair_with(accepted.server_node_description.role)
        {
            self.step = PairingStep::Failed;
            return Err(ConnectError::SameRole(self.local.role));
        }

        let challenge = self.challenge.as_ref().ok_or(ConnectError::OutOfOrder {
            got: "the server's acceptance",
            expected: "the start of pairing",
        })?;
        let binding = self.binding.as_ref().ok_or(ConnectError::ChallengeFailed)?;
        let expected = ChallengeResponse::compute(challenge, &self.code.token, binding)?;
        if !expected.verify(&accepted.client_hmac_challenge_response) {
            self.step = PairingStep::Failed;
            return Err(ConnectError::ChallengeFailed);
        }

        // Which side is the communication server is decided by the two deployments and
        // the two roles, never by preference.
        let server_deployment = accepted
            .server_endpoint_description
            .deployment
            .unwrap_or(Deployment::Lan);
        let (cem, rm) = if self.local.role == Role::Cem {
            (local_deployment, server_deployment)
        } else {
            (server_deployment, local_deployment)
        };
        let communication_server = Deployment::communication_server(cem, rm);
        self.communication_server = Some(communication_server);

        self.accepted = Some(accepted);
        self.step = PairingStep::Authenticated;
        Ok(if communication_server == self.local.role {
            NextStep::PostConnectionDetails
        } else {
            NextStep::RequestConnectionDetails
        })
    }

    /// Step 5: `R_s`, the answer to the server's challenge, Base64.
    ///
    /// Goes in the body of whichever of 6A and 6B [`Self::accept`] selected.
    pub fn server_challenge_response(&self) -> Result<String, ConnectError> {
        let accepted = self.accepted.as_ref().ok_or(ConnectError::OutOfOrder {
            got: "a challenge response",
            expected: "the server's acceptance",
        })?;
        let binding = self.binding.as_ref().ok_or(ConnectError::OutOfOrder {
            got: "a challenge response",
            expected: "the server's acceptance",
        })?;
        let challenge = super::base64_decode(&accepted.server_hmac_challenge)
            .ok_or(ConnectError::ChallengeFailed)?;
        Ok(ChallengeResponse::compute(&challenge, &self.code.token, binding)?.as_base64())
    }

    /// Step 6A: the body to send when the pairing server is the communication server.
    pub fn request_connection_details(&self) -> Result<ConnectionDetailsRequest, ConnectError> {
        Ok(ConnectionDetailsRequest {
            server_hmac_challenge_response: self.server_challenge_response()?,
        })
    }

    /// Step 6B: the body to send when *this* node is the communication server.
    pub fn post_connection_details(
        &mut self,
        details: ConnectionDetails,
        now: Timestamp,
    ) -> Result<ConnectionDetailsPost, ConnectError> {
        let response = self.server_challenge_response()?;
        self.connection_details(details.clone(), now)?;
        Ok(ConnectionDetailsPost {
            server_hmac_challenge_response: response,
            connection_details: details,
        })
    }

    /// Record the connection details, however they arrived.
    pub fn connection_details(
        &mut self,
        details: ConnectionDetails,
        now: Timestamp,
    ) -> Result<(), ConnectError> {
        self.expect(PairingStep::Authenticated)?;
        self.within_budget(now)?;
        self.details = Some(details);
        self.step = PairingStep::DetailsExchanged;
        Ok(())
    }

    /// Step 8: the body of `finalizePairing`, and the pairing to store.
    pub fn finalize(&mut self, now: Timestamp) -> Result<(FinalizePairing, Pairing), ConnectError> {
        self.expect(PairingStep::DetailsExchanged)?;
        self.within_budget(now)?;
        let accepted = self.accepted.take().ok_or(ConnectError::OutOfOrder {
            got: "finalization",
            expected: "the server's acceptance",
        })?;
        let details = self.details.take().ok_or(ConnectError::OutOfOrder {
            got: "finalization",
            expected: "connection details",
        })?;
        self.step = PairingStep::Paired;
        Ok((
            FinalizePairing { success: true },
            Pairing {
                local: self.local.id,
                remote: accepted.server_node_description,
                remote_endpoint: accepted.server_endpoint_description,
                details,
                communication_server: self.communication_server.unwrap_or(Role::Cem),
                s2_message_versions: self.s2_message_versions.clone(),
            },
        ))
    }

    /// Give up, telling the server so. `S2C §8`: the client may finalize with
    /// `success: false` "to let the server know it was not satisfied".
    pub fn abandon(&mut self) -> FinalizePairing {
        self.step = PairingStep::Failed;
        FinalizePairing { success: false }
    }

    fn expect(&mut self, step: PairingStep) -> Result<(), ConnectError> {
        if self.step == step {
            return Ok(());
        }
        let got = self.step.name();
        self.step = PairingStep::Failed;
        Err(ConnectError::OutOfOrder {
            got,
            expected: step.name(),
        })
    }

    fn within_budget(&mut self, now: Timestamp) -> Result<(), ConnectError> {
        if now.saturating_duration_since(self.started) > PAIRING_BUDGET {
            self.step = PairingStep::Failed;
            return Err(ConnectError::Expired {
                what: "pairing",
                limit: PAIRING_BUDGET,
            });
        }
        Ok(())
    }
}

