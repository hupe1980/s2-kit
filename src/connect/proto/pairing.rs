/// How long a whole pairing attempt may take.
///
/// `S2C §Pairing`: "the pairing attempt must be finished within 15 seconds". Each side
/// keeps its own budget, because each side can only see its own clock.
pub const PAIRING_BUDGET: Duration = Duration::from_secs(15);

/// The delay the server must insert before answering `requestPairing`.
///
/// `S2C §2. Calculate clientHmacChallengeResponse`: "To mitigate brute-force attacks, the
/// server **must** enforce a mandatory delay of one second before sending its response to
/// the client. For any given node at the server, pairing attempts **must** be handled
/// sequentially, such that each second only one pairing attempt can be processed for a
/// node."
pub const MINIMUM_SERVER_DELAY: Duration = Duration::from_secs(1);

