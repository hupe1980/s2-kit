/// The pairing server: the side that holds the token and answers.
///
/// It carries the two rules a request handler tends to lose — one attempt per node per
/// second, and a response delayed by at least a second — as state rather than as
/// discipline. `s2energy`'s S2 Connect layer has exactly these as an open issue.
#[derive(Debug)]
pub struct PairingServer {
    local: NodeDescription,
    local_endpoint: EndpointDescription,
    binding: HmacBinding,
    s2_message_versions: Vec<ProtocolVersion>,
    protocols: Vec<CommunicationProtocol>,
    /// The attempt currently in flight, if any.
    attempt: Option<Attempt>,
    /// When the last attempt for this node finished, for the rate limit.
    last_finished: Option<Timestamp>,
    /// The answer we owe the client, held until the mandatory second has elapsed.
    pending: Option<(Timestamp, PairingAccepted)>,
}

#[derive(Debug)]
struct Attempt {
    id: PairingAttemptId,
    started: Timestamp,
    /// `C_s`, kept so the client's `R_s` can be checked against it.
    expected_response: ChallengeResponse,
    client: NodeDescription,
    client_endpoint: EndpointDescription,
    s2_message_versions: Vec<ProtocolVersion>,
    details: Option<ConnectionDetails>,
    verified: bool,
}

impl PairingServer {
    /// A server for one node, bound to the identity clients will verify against.
    #[must_use]
    pub fn new(
        local: NodeDescription,
        local_endpoint: EndpointDescription,
        binding: HmacBinding,
    ) -> Self {
        Self {
            local,
            local_endpoint,
            binding,
            s2_message_versions: alloc::vec![
                crate::types::WireProfile::V1_0_0.connect_version(),
                crate::types::WireProfile::V0_0_2Beta.connect_version(),
            ],
            protocols: alloc::vec![CommunicationProtocol::WebSocket],
            attempt: None,
            last_finished: None,
            pending: None,
        }
    }

    /// Offer a different set of S2 JSON message versions, newest first.
    #[must_use]
    pub fn with_s2_message_versions(mut self, versions: Vec<ProtocolVersion>) -> Self {
        self.s2_message_versions = versions;
        self
    }

    /// Steps 2 and 3: handle `requestPairing`.
    ///
    /// Returns the `200` body **and the instant before which it may not be sent**. The
    /// delay is not advisory: with a four-character token there are 14.7 million
    /// possibilities, and one guess per second is the difference between a brute force
    /// taking months and taking an afternoon.
    ///
    /// A refusal consumes the rate-limit slot just as a success does, which is what makes
    /// the limit worth anything.
    ///
    /// # Errors
    ///
    /// [`ConnectError::RateLimited`] should become `503`; a [`PairingRefused`] carried in
    /// [`ConnectError::Refused`] should become `400` with that body.
    pub fn request_pairing(
        &mut self,
        request: &PairingRequest,
        token: &PairingToken,
        server_challenge: &[u8],
        attempt_id: PairingAttemptId,
        now: Timestamp,
    ) -> Result<(Timestamp, PairingAccepted), ConnectError> {
        if let Some(attempt) = &self.attempt
            && now.saturating_duration_since(attempt.started) <= PAIRING_BUDGET
        {
            return Err(ConnectError::RateLimited);
        }
        if let Some(finished) = self.last_finished
            && now.saturating_duration_since(finished) < MINIMUM_SERVER_DELAY
        {
            return Err(ConnectError::RateLimited);
        }

        let result = self.answer(request, token, server_challenge, attempt_id, now);
        if result.is_err() {
            self.last_finished = Some(now);
            self.attempt = None;
        }
        result
    }

    fn answer(
        &mut self,
        request: &PairingRequest,
        token: &PairingToken,
        server_challenge: &[u8],
        attempt_id: PairingAttemptId,
        now: Timestamp,
    ) -> Result<(Timestamp, PairingAccepted), ConnectError> {
        use PairingErrorMessage as E;

        // The checks in the order `S2C §1. Request pairing` tabulates them.
        if !self
            .local
            .role
            .can_pair_with(request.client_node_description.role)
        {
            return Err(refused(E::InvalidCombinationOfRoles));
        }
        if !request
            .supported_hmac_hashing_algorithms
            .contains(&HmacHashingAlgorithm::Sha256)
        {
            return Err(refused(E::IncompatibleHmacHashingAlgorithms));
        }
        if !request
            .supported_communication_protocols
            .iter()
            .any(|p| self.protocols.contains(p))
        {
            return Err(refused(E::IncompatibleCommunicationProtocols));
        }
        // A version mismatch is refusable, but `forcePairing` overrides it: the nodes
        // pair now and talk after a software update.
        let common = request
            .supported_s2_message_versions
            .iter()
            .filter(|v| self.s2_message_versions.iter().any(|ours| ours.matches(v)))
            .cloned()
            .collect::<Vec<_>>();
        if common.is_empty() && !request.force_pairing {
            return Err(refused(E::IncompatibleS2MessageVersions));
        }
        if request.node_id.is_some() && request.node_id_alias.is_some() {
            return Err(refused(E::ParsingError));
        }

        let client_challenge = super::base64_decode(&request.client_hmac_challenge)
            .ok_or_else(|| refused(E::ParsingError))?;
        // `R_c`: prove to the client that we hold the token and are the identity it
        // reached.
        let client_response = ChallengeResponse::compute(&client_challenge, token, &self.binding)?;
        // `C_s` / the response we will expect back in step 6.
        let expected_response = ChallengeResponse::compute(server_challenge, token, &self.binding)?;

        let accepted = PairingAccepted {
            pairing_attempt_id: attempt_id.clone(),
            server_node_description: self.local.clone(),
            server_endpoint_description: self.local_endpoint.clone(),
            selected_hmac_hashing_algorithm: HmacHashingAlgorithm::Sha256,
            client_hmac_challenge_response: client_response.as_base64(),
            server_hmac_challenge: super::base64_encode(server_challenge),
        };

        self.attempt = Some(Attempt {
            id: attempt_id,
            started: now,
            expected_response,
            client: request.client_node_description.clone(),
            client_endpoint: request.client_endpoint_description.clone(),
            s2_message_versions: common,
            details: None,
            verified: false,
        });
        let send_after = now.checked_add(MINIMUM_SERVER_DELAY).unwrap_or(now);
        self.pending = Some((send_after, accepted.clone()));
        Ok((send_after, accepted))
    }

    /// When the driver should next do something: the moment the delayed answer becomes
    /// sendable, or the moment the attempt's budget runs out.
    #[must_use]
    pub fn poll_timeout(&self) -> Option<Timestamp> {
        self.pending.as_ref().map(|(at, _)| *at).or_else(|| {
            self.attempt
                .as_ref()
                .map(|a| a.started.checked_add(PAIRING_BUDGET).unwrap_or(a.started))
        })
    }

    /// Take the delayed answer, if the mandatory second has elapsed.
    ///
    /// Returning `None` early is the point: a driver that loops on this cannot answer
    /// sooner than the specification allows, however tempting it is to.
    pub fn poll_response(&mut self, now: Timestamp) -> Option<PairingAccepted> {
        let (at, _) = self.pending.as_ref()?;
        if now < *at {
            return None;
        }
        self.pending.take().map(|(_, accepted)| accepted)
    }

    /// Authenticate a step-6-or-later request by its bearer.
    ///
    /// A `false` here is a `401`, and `S2C-OAS` says the client "may restart the pairing
    /// process by calling /requestPairing again" — so it must not fail the attempt.
    #[must_use]
    pub fn authenticates(&self, bearer: &str) -> bool {
        self.attempt.as_ref().is_some_and(|a| a.id.verify(bearer))
    }

    /// Steps 7A and 7B: check `serverHmacChallengeResponse`.
    ///
    /// A `false` here is a `403`: `S2C-OAS` — "The PairingAttempt has failed and cannot
    /// proceed", so the attempt is dropped rather than merely refused.
    pub fn verify_client(&mut self, response: &str, now: Timestamp) -> Result<(), ConnectError> {
        let Some(attempt) = self.attempt.as_mut() else {
            return Err(ConnectError::OutOfOrder {
                got: "a challenge response",
                expected: "the start of pairing",
            });
        };
        if now.saturating_duration_since(attempt.started) > PAIRING_BUDGET {
            self.fail(now);
            return Err(ConnectError::Expired {
                what: "pairing",
                limit: PAIRING_BUDGET,
            });
        }
        if !attempt.expected_response.verify(response) {
            self.fail(now);
            return Err(ConnectError::ChallengeFailed);
        }
        attempt.verified = true;
        Ok(())
    }

    /// Step 7A: what to answer `requestConnectionDetails` with, once verified.
    pub fn connection_details(
        &mut self,
        details: ConnectionDetails,
    ) -> Result<ConnectionDetails, ConnectError> {
        let attempt = self.attempt.as_mut().ok_or(ConnectError::OutOfOrder {
            got: "connection details",
            expected: "the start of pairing",
        })?;
        if !attempt.verified {
            return Err(ConnectError::ChallengeFailed);
        }
        attempt.details = Some(details.clone());
        Ok(details)
    }

    /// Step 7B: record the details the client posted, once verified.
    pub fn accept_connection_details(
        &mut self,
        details: ConnectionDetails,
    ) -> Result<(), ConnectError> {
        self.connection_details(details).map(|_| ())
    }

    /// Step 8: handle `finalizePairing`, yielding the pairing to store.
    ///
    /// A `success: false` is not an error — it is the client saying it could not proceed —
    /// but it yields no pairing.
    pub fn finalize(
        &mut self,
        body: FinalizePairing,
        now: Timestamp,
    ) -> Result<Option<Pairing>, ConnectError> {
        let Some(attempt) = self.attempt.take() else {
            return Err(ConnectError::OutOfOrder {
                got: "finalization",
                expected: "the start of pairing",
            });
        };
        self.last_finished = Some(now);
        self.pending = None;

        if now.saturating_duration_since(attempt.started) > PAIRING_BUDGET {
            return Err(ConnectError::Expired {
                what: "pairing",
                limit: PAIRING_BUDGET,
            });
        }
        if !body.success {
            return Ok(None);
        }
        if !attempt.verified {
            return Err(ConnectError::ChallengeFailed);
        }
        let details = attempt.details.ok_or(ConnectError::OutOfOrder {
            got: "finalization",
            expected: "connection details",
        })?;
        let client_deployment = attempt
            .client_endpoint
            .deployment
            .unwrap_or(Deployment::Lan);
        let own_deployment = self.local_endpoint.deployment.unwrap_or(Deployment::Lan);
        let (cem, rm) = if self.local.role == Role::Cem {
            (own_deployment, client_deployment)
        } else {
            (client_deployment, own_deployment)
        };
        Ok(Some(Pairing {
            local: self.local.id,
            remote: attempt.client,
            remote_endpoint: attempt.client_endpoint,
            details,
            communication_server: Deployment::communication_server(cem, rm),
            s2_message_versions: attempt.s2_message_versions,
        }))
    }

    fn fail(&mut self, now: Timestamp) {
        self.attempt = None;
        self.pending = None;
        self.last_finished = Some(now);
    }
}

fn refused(message: PairingErrorMessage) -> ConnectError {
    ConnectError::Refused(PairingRefused {
        error_message: message,
        additional_info: None,
    })
}

